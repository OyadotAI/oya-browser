import assert from 'node:assert/strict';
import * as flow from './src/flow-recorder.js';

let unblock;
let delayed = false;
let failStop = false;
const calls = [];
const first = { id: 'doc:1', action: 'click', el: { domId: 'one' }, t: 1 };
const second = { id: 'doc:2', action: 'click', el: { domId: 'two' }, t: 1 };
const dispatch = async (_action, { mode }) => {
  calls.push(mode);
  if (mode === 'drain' && delayed) await new Promise(resolve => { unblock = resolve; });
  if (mode === 'stop' && failStop) return { ok: false, error: 'lost connection' };
  return { ok: true, data: { steps: mode === 'start' ? [] : [first, second], secrets: [] } };
};
await flow.start('one', dispatch);
delayed = true;
const pending = flow.status('one', dispatch);
await Promise.resolve();
const stopping = flow.stop('one', dispatch);
assert.deepEqual(calls, ['start', 'drain'], 'stop waits for the in-flight poll');
unblock();
await pending;
const stopped = await stopping;
assert.equal(stopped.recording, false);
assert.equal(stopped.steps.length, 2, 'same-millisecond clicks on distinct elements survive');
assert.deepEqual(await flow.status('one', dispatch), stopped, 'stopped data survives another status request');
assert.equal(calls.length, 3, 'stopped status does not command a browser already handed back');
await flow.start('one', dispatch);
assert.equal((await flow.status('one')).steps.length, 0, 'start clears the previous recording');
await assert.rejects(flow.discard('one'), /Stop the recording/);
failStop = true;
await assert.rejects(flow.stop('one', dispatch), /lost connection/);
assert.equal(flow.isRecording('one'), true, 'a failed stop is visible and retryable');
failStop = false;
await flow.stop('one', dispatch);
await flow.discard('one');
assert.deepEqual(await flow.status('one'), { recording: false, steps: [], secrets: [] });
console.log('flow recorder: ok');
